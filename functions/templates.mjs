export function planForProfile(condition, extraConditions = []) {
  const base = templateFor(condition);
  const extras = [...new Set((Array.isArray(extraConditions) ? extraConditions : [])
    .filter((id) => CONDITION_IDS.includes(id) && id !== condition))];
  return {
    ...base,
    condition,
    guidelines: [...new Set([...base.guidelines, ...extras.flatMap((id) => COMORBIDITY_GUIDELINES[id] ?? [])])],
    avoid: [...new Set([...base.avoid, ...extras.flatMap((id) => COMORBIDITY_AVOID[id] ?? [])])],
    comorbidities: extras,
  };
}

export function templateFor(condition) {
  return PLAN_TEMPLATES.find((item) => item.condition === condition) ?? PLAN_TEMPLATES[0];
}

export function conditionLabel(id) {
  return CONDITIONS.find((item) => item.id === id)?.label ?? 'متابعة عامة';
}

export function defaultTargetCalories(condition) {
  return templateFor(condition).target_calories;
}
